/// <summary>
/// 캐릭터가 사용하는 무기 종류.
///
/// 사거리 분류:
///   - 근거리: SG, SMG
///   - 중거리: AR, MG
///   - 원거리: SR
///   - 거리무관: RL (런처는 적정 사거리 개념이 없음)
///
/// 실제 매핑은 WeaponSpecs 에서 관리.
/// </summary>
public enum WeaponType
{
    SG  = 0, // 샷건 — 근거리 광폭 피해
    SMG = 1, // 기관단총 — 근거리 고연사
    AR  = 2, // 소총 — 중거리 범용
    MG  = 3, // 머신건 — 중거리 다탄/고연사
    SR  = 4, // 저격소총 — 원거리 정밀
    RL  = 5  // 런처 — 광역 / 거리 무관
}
